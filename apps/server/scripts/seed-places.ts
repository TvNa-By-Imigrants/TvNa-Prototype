async function main(): Promise<void> {
  console.log(`[seed-places] seeding ${initialPlaces.length} places into database...`);

  for (const item of initialPlaces) {
    const existing = await db
      .select({ id: place.id })
      .from(place)
      .where(eq(place.id, item.id))
      .limit(1);

    if (existing.length === 0) {
      await db.insert(place).values({
        id: item.id,
        name: item.name,
        nameKm: item.nameKm,
        area: item.area,
        province: item.province,
        category: item.category,
        categoryId: item.categoryId,
        image: item.image,
        rating: item.rating,
        reviewsCount: item.reviewsCount,
        priceLevel: item.priceLevel,
        hours: item.hours,
        isPartnered: item.isPartnered,
        is24Hours: item.is24Hours,
        address: item.address,
        description: item.description,
        lat: item.lat,
        lng: item.lng,
        tags: item.tags,
      });
      console.log(`  + inserted: ${item.id} (${item.name})`);
    } else {
      await db
        .update(place)
        .set({
          name: item.name,
          nameKm: item.nameKm,
          area: item.area,
          province: item.province,
          category: item.category,
          categoryId: item.categoryId,
          image: item.image,
          rating: item.rating,
          reviewsCount: item.reviewsCount,
          priceLevel: item.priceLevel,
          hours: item.hours,
          isPartnered: item.isPartnered,
          is24Hours: item.is24Hours,
          address: item.address,
          description: item.description,
          lat: item.lat,
          lng: item.lng,
          tags: item.tags,
          updatedAt: new Date(),
        })
        .where(eq(place.id, item.id));
      console.log(`  ~ updated: ${item.id} (${item.name})`);
    }
  }

  console.log('[seed-places] complete.');
}

main()
  .then(() => process.exit(0))
  .catch((error: unknown) => {
    console.error('[seed-places] error:', error);
    process.exit(1);
  });
